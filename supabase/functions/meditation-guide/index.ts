import { serve } from "https://deno.land/std@0.168.0/http/server.ts";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers":
    "authorization, x-client-info, apikey, content-type, x-supabase-client-platform, x-supabase-client-platform-version, x-supabase-client-runtime, x-supabase-client-runtime-version",
};

serve(async (req) => {
  if (req.method === "OPTIONS") return new Response(null, { headers: corsHeaders });

  try {
    const { emotionName, messages } = await req.json();
    const LOVABLE_API_KEY = Deno.env.get("LOVABLE_API_KEY");
    if (!LOVABLE_API_KEY) throw new Error("LOVABLE_API_KEY is not configured");

    const systemPrompt = `You are an experienced yoga and meditation instructor specializing in breathwork and emotional regulation. The user has selected the emotion "${emotionName || "Fear"}" from the Fear family.

Your role:
- Start by warmly acknowledging their emotion in 1-2 sentences
- Then guide them through a 2-minute box breathing exercise (4 seconds breathe in, 4 seconds hold, 4 seconds breathe out, 4 seconds hold)
- Be warm, calming, and conversational
- Use phrases like "breathe in slowly... hold... now exhale gently..."
- Give clear timing cues that match the 4-second rhythm
- Keep each response concise — 2-3 sentences at a time
- After the initial greeting, focus purely on breathing guidance
- Use ellipses (...) to create a sense of pacing and calm
- Do NOT use markdown headers or bullet points — speak naturally as if talking to someone in person
- End the session after about 2 minutes with an encouraging closing message`;

    const allMessages = [
      { role: "system", content: systemPrompt },
      ...(messages || [{ role: "user", content: `I'm feeling ${emotionName || "fear"}. Please guide me through a breathing exercise.` }]),
    ];

    const response = await fetch("https://ai.gateway.lovable.dev/v1/chat/completions", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${LOVABLE_API_KEY}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model: "google/gemini-3-flash-preview",
        messages: allMessages,
        stream: true,
      }),
    });

    if (!response.ok) {
      if (response.status === 429) {
        return new Response(JSON.stringify({ error: "Rate limited. Please try again shortly." }), {
          status: 429,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      if (response.status === 402) {
        return new Response(JSON.stringify({ error: "AI credits exhausted. Please add credits." }), {
          status: 402,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      const t = await response.text();
      console.error("AI gateway error:", response.status, t);
      return new Response(JSON.stringify({ error: "AI gateway error" }), {
        status: 500,
        headers: { ...corsHeaders, "Content-Type": "application/json" },
      });
    }

    return new Response(response.body, {
      headers: { ...corsHeaders, "Content-Type": "text/event-stream" },
    });
  } catch (e) {
    console.error("meditation-guide error:", e);
    return new Response(JSON.stringify({ error: e instanceof Error ? e.message : "Unknown error" }), {
      status: 500,
      headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  }
});
